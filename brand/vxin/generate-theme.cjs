// Source of truth: theme.json. Run from any directory; --check detects drift.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname,'../..');
const t = JSON.parse(fs.readFileSync(path.join(__dirname,'theme.json'),'utf8'));
const check = process.argv.includes('--check');
let drift = false;
function emit(file,value) {
  const target=path.join(root,file);
  const old=fs.existsSync(target)?fs.readFileSync(target,'utf8').replace(/\r\n/g,'\n'):'';
  if(old===value) return;
  if(check) { console.error('Theme drift: '+file); drift=true; return; }
  fs.mkdirSync(path.dirname(target),{recursive:true}); fs.writeFileSync(target,value);
}
const keys=Object.keys(t.colors.light);
const kotlinColor=c=>'Color(0xFF'+c.slice(1)+')';
let kt='// Generated by brand/vxin/generate-theme.cjs. Do not edit.\npackage com.vxin.app.ui.theme\n\nimport androidx.compose.ui.graphics.Color\nimport androidx.compose.runtime.staticCompositionLocalOf\n\ndata class VxinPalette(\n'+keys.map(k=>'    val '+k+': Color,').join('\n')+'\n)\n';
for(const mode of ['light','dark']) kt+='\nval Vxin'+(mode==='light'?'Light':'Dark')+'Palette = VxinPalette(\n'+keys.map(k=>'    '+k+' = '+kotlinColor(t.colors[mode][k])+',').join('\n')+'\n)\n';
kt+='\nval LocalVxinPalette = staticCompositionLocalOf { VxinLightPalette }\n';
emit('android/app/src/main/java/com/vxin/app/ui/theme/GeneratedPalette.kt',kt);
let swift='// Generated by brand/vxin/generate-theme.cjs. Do not edit.\nimport SwiftUI\nimport UIKit\n\nextension Color {\n    private static func adaptive(_ light: UInt32, _ dark: UInt32) -> Color {\n        Color(uiColor: UIColor { traits in\n            let rgb = traits.userInterfaceStyle == .dark ? dark : light\n            return UIColor(red: CGFloat((rgb >> 16) & 255) / 255, green: CGFloat((rgb >> 8) & 255) / 255, blue: CGFloat(rgb & 255) / 255, alpha: 1)\n        })\n    }\n';
const aliases={vxinBg:'bg',vxinSurface:'surface',vxinSurface2:'surface2',vxinCanvas:'canvas',vxinBorder:'border',vxinBrand:'primary',vxinBrandLight:'primaryHover',vxinBrandDark:'primaryActive',vxinBrandMuted:'primaryTint',vxinOnPrimary:'onPrimary',vxinLink:'link',vxinTextPrimary:'text',vxinTextSecondary:'text2',vxinTextMuted:'text3',vxinError:'danger',vxinOnline:'online',vxinBubbleMine:'bubbleMine',vxinBubbleMineText:'bubbleMineText',vxinBubbleText:'text',vxinBubbleOther:'bubbleOther',vxinDisabledFill:'disabledFill',vxinAuthBg:'bg',vxinAuthSurface:'surface',vxinAuthGold:'link',vxinAuthGoldHover:'primaryHover',vxinAuthBorder:'border',vxinAuthTextSecondary:'text2',vxinAuthTextMuted:'text2',vxinAuthPlaceholder:'text3'};
for(const [name,key] of Object.entries(aliases)) swift+='    static let '+name+' = adaptive(0x'+t.colors.light[key].slice(1)+', 0x'+t.colors.dark[key].slice(1)+')\n';
for(const [name,value] of Object.entries({vxinGreen:'vxinBrand',vxinTeal:'vxinBrand',vxinSuccess:'vxinOnline',vxinPay:'vxinBrand',vxinPayGradStart:'vxinBrand',vxinPayGradEnd:'vxinBrand',vxinInfoBannerFg:'vxinLink',vxinCard:'vxinSurface'})) swift+='    static let '+name+' = '+value+'\n';
swift+='}\n\nextension LinearGradient {\n';
for(const [name,color] of Object.entries({vxinBrand:'vxinBrand',vxinBubble:'vxinBubbleMine',vxinPay:'vxinPay'})) swift+='    static let '+name+' = LinearGradient(colors: [.'+color+', .'+color+'], startPoint: .topLeading, endPoint: .bottomTrailing)\n';
swift+='}\n';
emit('ios/Vxin/UI/Theme/Theme.swift',swift);
let css=fs.readFileSync(path.join(root,'web/src/styles/native-theme.css'),'utf8').replace(/\r\n/g,'\n');
const boundary=css.indexOf(':root body.dark-mode {');
let sections=[css.slice(0,boundary),css.slice(boundary)];
for(const [i,mode] of ['light','dark'].entries()) for(const [key,prop] of Object.entries(t.cssProperties)) sections[i]=sections[i].replace(new RegExp('(--nt-'+prop+':\\s*)#[0-9a-fA-F]{6}(;)'),(_,a,b)=>a+t.colors[mode][key]+b);
for(const [i,mode] of ['light','dark'].entries()) {
  for(const key of ['primary','danger','badge','bubbleMine']) {
    const prop=t.cssProperties[key];
    const rgb=t.colors[mode][key].slice(1).match(/../g).map(v=>parseInt(v,16)).join(', ');
    sections[i]=sections[i].replace(new RegExp('(--nt-'+prop+'-rgb:\\s*)[0-9, ]+(;)'),(_,a,b)=>a+rgb+b);
  }
}
css=sections.join('');
for(const [name,value] of Object.entries(t.radii)) css=css.replace(new RegExp('(--nt-r-'+name+':\\s*)[0-9]+px;'),(_,a)=>a+value+'px;');
emit('web/src/styles/native-theme.css',css);
for(const [file,format] of [['android/app/src/main/java/com/vxin/app/ui/theme/Dimens.kt','kotlin'],['ios/Vxin/UI/Theme/Dimens.swift','swift']]) {
  let source=fs.readFileSync(path.join(root,file),'utf8').replace(/\r\n/g,'\n');
  for(const [name,value] of Object.entries(t.radii)) source=source.replace(new RegExp('(\\b(?:val|let) '+name+'(?:: CGFloat)?\\s*= )\\d+(\\.dp)?'),(_,a,b)=>a+value+(b||''));
  emit(file,source);
}
emit('desktop-electron/assets/theme.json',JSON.stringify(t.colors,null,2)+'\n');
if(drift) process.exitCode=1;
else console.log(check?'Theme outputs are synchronized.':'Theme outputs generated.');
